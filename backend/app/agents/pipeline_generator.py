"""
PipelineGenerator — Phase 8.

Converts approved recommendations into ordered pipeline steps
and generates readable Python transformation code.
"""
from __future__ import annotations

from typing import Any


# Mapping: action → step template
ACTION_STEP_MAP: dict[str, dict] = {
    "remove_duplicates": {"operation": "remove_duplicates"},
    "fill_missing": {"operation": "fill_missing"},
    "clip_outliers": {"operation": "clip_outliers"},
    "standardise_categories": {"operation": "standardise_categories"},
    "parse_dates": {"operation": "parse_dates"},
    "drop_column": {"operation": "drop_column"},
    "rename_column": {"operation": "rename_column"},
    "cast_numeric": {"operation": "cast_numeric"},
    "drop_high_missing": {"operation": "drop_high_missing"},
}

# Priority order (lower = runs first)
OPERATION_ORDER: dict[str, int] = {
    "drop_high_missing": 1,
    "remove_duplicates": 2,
    "cast_numeric": 3,
    "parse_dates": 4,
    "fill_missing": 5,
    "clip_outliers": 6,
    "standardise_categories": 7,
    "drop_column": 8,
    "rename_column": 9,
}


def generate_pipeline(
    recommendations: list[dict[str, Any]],
    dataset_name: str = "dataset",
) -> dict[str, Any]:
    """
    Convert applied recommendations into a pipeline.

    Returns:
        {
          "steps": list of step dicts,
          "code": Python code string,
          "name": pipeline name,
        }
    """
    applied = [r for r in recommendations if r.get("status") == "applied"]

    steps: list[dict] = []
    for idx, rec in enumerate(applied):
        action = rec.get("action", "")
        template = ACTION_STEP_MAP.get(action, {}).copy()
        if not template:
            continue

        step: dict[str, Any] = {
            "step": idx + 1,
            **template,
        }

        # Attach column / strategy if needed
        if rec.get("column"):
            step["column"] = rec["column"]
        if rec.get("strategy"):
            step["strategy"] = rec["strategy"]

        steps.append(step)

    # Sort by canonical order
    steps.sort(key=lambda s: OPERATION_ORDER.get(s.get("operation", ""), 99))

    # Re-number after sort
    for i, s in enumerate(steps, 1):
        s["step"] = i

    code = _generate_code(steps, dataset_name)

    return {
        "name": f"pipeline_{dataset_name.replace(' ', '_').lower()}",
        "steps": steps,
        "code": code,
    }


def _generate_code(steps: list[dict], dataset_name: str) -> str:
    lines: list[str] = [
        "# ============================================================",
        f"# Auto-generated transformation pipeline: {dataset_name}",
        "# Generated by AI Data Engineering Copilot",
        "# ============================================================",
        "",
        "import pandas as pd",
        "import numpy as np",
        "",
        f"# Load dataset",
        f'df = pd.read_csv("{dataset_name}.csv")  # adjust path as needed',
        f"print(f'Loaded {{len(df)}} rows, {{len(df.columns)}} columns')",
        "",
    ]

    for step in steps:
        op = step.get("operation", "")
        col = step.get("column")
        strategy = step.get("strategy")
        step_n = step.get("step")

        lines.append(f"# ---- Step {step_n}: {op} ----")

        if op == "remove_duplicates":
            lines += [
                "before_rows = len(df)",
                "df = df.drop_duplicates()",
                "print(f'Removed {before_rows - len(df)} duplicate rows')",
            ]

        elif op == "fill_missing" and col:
            if strategy == "median":
                lines += [
                    f"fill_val = df['{col}'].median()",
                    f"df['{col}'] = df['{col}'].fillna(fill_val)",
                    f"print(f\"Filled '{col}' with median={{fill_val:.4f}}\")",
                ]
            elif strategy == "mean":
                lines += [
                    f"fill_val = df['{col}'].mean()",
                    f"df['{col}'] = df['{col}'].fillna(fill_val)",
                    f"print(f\"Filled '{col}' with mean={{fill_val:.4f}}\")",
                ]
            elif strategy == "mode":
                lines += [
                    f"fill_val = df['{col}'].mode().iloc[0]",
                    f"df['{col}'] = df['{col}'].fillna(fill_val)",
                    f"print(f\"Filled '{col}' with mode={{fill_val}}\")",
                ]
            elif strategy == "ffill":
                lines += [f"df['{col}'] = df['{col}'].ffill()"]
            elif strategy == "bfill":
                lines += [f"df['{col}'] = df['{col}'].bfill()"]
            elif strategy == "drop_rows":
                lines += [
                    f"before_rows = len(df)",
                    f"df = df.dropna(subset=['{col}'])",
                    f"print(f'Dropped {{before_rows - len(df)}} rows with null {col}')",
                ]
            elif strategy == "unknown":
                lines += [f"df['{col}'] = df['{col}'].fillna('Unknown')"]
            elif strategy == "zero":
                lines += [f"df['{col}'] = df['{col}'].fillna(0)"]

        elif op == "clip_outliers" and col:
            lines += [
                f"q1 = df['{col}'].quantile(0.25)",
                f"q3 = df['{col}'].quantile(0.75)",
                f"iqr = q3 - q1",
                f"lower, upper = q1 - 1.5 * iqr, q3 + 1.5 * iqr",
                f"df['{col}'] = df['{col}'].clip(lower=lower, upper=upper)",
                f"print(f\"Clipped '{col}' to [{{lower:.4f}}, {{upper:.4f}}]\")",
            ]

        elif op == "standardise_categories" and col:
            lines += [
                f"df['{col}'] = df['{col}'].astype(str).str.strip().str.title()",
            ]

        elif op == "parse_dates" and col:
            lines += [
                f"df['{col}'] = pd.to_datetime(df['{col}'], format='mixed', errors='coerce')",
            ]

        elif op == "cast_numeric" and col:
            lines += [
                f"df['{col}'] = pd.to_numeric(df['{col}'], errors='coerce')",
            ]

        elif op == "drop_column" and col:
            lines += [f"df = df.drop(columns=['{col}'])"]

        lines.append("")

    lines += [
        "# ---- Final validation ----",
        "print(f'Final shape: {df.shape}')",
        "print(f'Missing values: {df.isna().sum().sum()}')",
        "print(f'Duplicate rows: {df.duplicated().sum()}')",
        "",
        f'df.to_csv("{dataset_name}_cleaned.csv", index=False)',
        f"print('Saved cleaned dataset to {dataset_name}_cleaned.csv')",
    ]

    return "\n".join(lines)
